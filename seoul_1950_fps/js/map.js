function isWallTile(tile) {
  return tile === TILE_BRICK || tile === TILE_CONCRETE || tile === TILE_RUBBLE || tile === TILE_SANDBAG;
}

function getTile(x, y) {
  const ix = Math.floor(x);
  const iy = Math.floor(y);
  if (ix < 0 || iy < 0 || ix >= MAP_WIDTH || iy >= MAP_HEIGHT) return TILE_CONCRETE;
  return WORLD_MAP[iy][ix];
}

function setTile(x, y, value) {
  const ix = Math.floor(x);
  const iy = Math.floor(y);
  if (ix < 0 || iy < 0 || ix >= MAP_WIDTH || iy >= MAP_HEIGHT) return;
  WORLD_MAP[iy][ix] = value;
}
